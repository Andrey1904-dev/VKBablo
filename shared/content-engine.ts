const BANKS: Record<CommunityId, Banks> = {
  stories: STORIES,
  milana: MILANA,
  life: LIFE,
  veronica: VERONICA,
};

export function ideaSeries(communityId: CommunityId): string | undefined {
  return communityId === "life"
    ? "Раньше и сейчас"
    : communityId === "milana"
      ? "Милана и Толечка"
      : communityId === "veronica"
        ? "Заметки Вероники"
        : undefined;
}

export function generateIdea(communityId: CommunityId, usedKeys: readonly string[], seed: string): Idea {
  const rand = mulberry32(seedFrom(seed + communityId));
  const bank = BANKS[communityId];
  for (let i = 0; i < 40; i++) {
    const topic = pick(rand, bank.topics);
    const hook = pick(rand, bank.hooks);
    const key = `${communityId}:${topic}:${hook.slice(0, 24)}`;
    if (usedKeys.includes(key)) continue;
    return {
      key,
      topic,
      title: topic[0].toUpperCase() + topic.slice(1),
      angle: hook,
      series: ideaSeries(communityId),
    };
  }
  const topic = pick(rand, bank.topics);
  return {
    key: `${communityId}:${topic}:${seed}`,
    topic,
    title: topic[0].toUpperCase() + topic.slice(1),
    angle: pick(rand, bank.hooks),
    series: ideaSeries(communityId),
  };
}

/** Пул идей для студии: несколько различных вариантов за раз. */
export function generateIdeas(communityId: CommunityId, usedKeys: readonly string[], seed: string, count = 6): Idea[] {
  const out: Idea[] = [];
  for (let i = 0; i < count * 3 && out.length < count; i++) {
    const idea = generateIdea(communityId, [...usedKeys, ...out.map((o) => o.key)], `${seed}:${i}`);
    if (!out.some((o) => o.key === idea.key)) out.push(idea);
  }
  return out;
}

export function generateText(communityId: CommunityId, idea: Idea, seed: string): string {
  const rand = mulberry32(seedFrom(seed + "text" + idea.key));
  const bank = BANKS[communityId];
  const extra =
    communityId === "milana"
      ? pick(rand, ["светлом пальто", "атласной блузке", "очках", "с идеальными стрелками"])
      : communityId === "life"
        ? pick(rand, [
            "мы ждали звонка у окна",
            "плёнку сдавали и не знали, что получится",
            "в лифте разговаривали с соседями",
            "праздник начинался с открытки, а не с истории",
          ])
        : "";
  const body = pick(rand, bank.bodies)({ rand, name: "", extra });
  const end = pick(rand, bank.endings);
  const parts = [idea.angle, "", body, "", end];
  if (communityId === "veronica" && !parts.join(" ").includes("?")) {
    parts.push("", pick(rand, VERONICA.endings));
  }
  return parts.join("\n");
}

export function titleForTopic(communityId: CommunityId, topic: string): string {
  return topic ? topic[0].toUpperCase() + topic.slice(1) : communityId;
}
